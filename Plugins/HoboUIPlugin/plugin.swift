import Foundation
import PackagePlugin

/// Embeds `hobo-ui`, the macOS guests' accessibility driver, in `HoboVM` as Swift source, as
/// `HoboAgentPlugin` does the agent: `make install` copies only `hobo`. Host and guest are both
/// arm64 macOS, so the tool SwiftPM builds for the host is the guest's binary.
@main
struct HoboUIPlugin: BuildToolPlugin {
    func createBuildCommands(context: PluginContext, target: Target) async throws -> [Command] {
        let tool = try context.tool(named: "hobo-ui").url
        let output = context.pluginWorkDirectoryURL.appending(path: "HoboUIBinary.swift")
        // Backticks, not $(…), which the build system would take for one of its settings and expand to nothing.
        let script = #"""
            data=`base64 -i "$1"` && test -n "$data" &&
            printf '// Generated by HoboUIPlugin.\nimport Foundation\n\nenum HoboUIBinary {\n    static let darwin = Data(base64Encoded: "%s")!\n}\n' "$data" > "$2"
            """#
        return [.buildCommand(
            displayName: "Embedding hobo-ui",
            executable: URL(filePath: "/bin/sh"),
            arguments: ["-c", script, "embed", tool.path, output.path],
            inputFiles: [tool],
            outputFiles: [output]
        )]
    }
}
