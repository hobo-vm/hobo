// Writes README.md's feature tour, between its features:start and features:end markers, from the
// short part of each docs/features/*.md. With --check, writes nothing and fails with a diff if
// README.md isn't what this would write (make readme-check, and the site build).
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { posix } from 'node:path';
import { loadFeatures, repoRoot, resolveLink, siteURL } from './features.mjs';

const start = '<!-- features:start -->';
const end = '<!-- features:end -->';
const readmePath = posix.join(repoRoot, 'README.md');

function featureTour(features) {
  const pageURL = (slug) => `${siteURL}/${slug}/`;
  const sections = features.map((feature) => {
    // README.md is at the repo root, so a link to another repo file is just its repo-relative path.
    const short = feature.short.replace(/(\]\()([^)\s]+)/g, (_, open, target) =>
      open + resolveLink(feature.file, target, { page: pageURL, repoFile: (path) => path }));
    return `### ${feature.title}\n\n${short}\n\nFull guide → [hobo.gsquared.app/${feature.slug}](${pageURL(feature.slug)})`;
  });
  return [start, '<!-- Generated by `make readme` from docs/features/*.md: edit those, not this. -->', ...sections, end].join('\n\n');
}

function render(readme) {
  const from = readme.indexOf(start);
  const to = readme.indexOf(end);
  if (from < 0 || to < from) throw new Error(`README.md needs ${start} and then ${end}`);
  return readme.slice(0, from) + featureTour(loadFeatures()) + readme.slice(to + end.length);
}

const current = readFileSync(readmePath, 'utf8');
let wanted;
try {
  wanted = render(current);
} catch (error) {
  console.error(error.message);
  process.exit(1);
}
if (wanted === current) process.exit(0);
if (process.argv.includes('--check')) {
  spawnSync('diff', ['-u', '--label', 'README.md', '--label', 'README.md (from docs/features)', readmePath, '-'], {
    input: wanted,
    stdio: ['pipe', 'inherit', 'inherit'],
  });
  console.error('README.md is out of date with docs/features: run make readme');
  process.exit(1);
}
writeFileSync(readmePath, wanted);
