#!/bin/sh
# Builds hobo-agent for each guest and writes the binaries as Swift source for HoboVM to embed:
# build.sh <source directory> <output Swift file> <scratch directory>. Run by HoboAgentPlugin.
set -eu
source=$1 output=$2 scratch=$3

go=$(PATH="$PATH:/opt/homebrew/bin:/usr/local/bin:/usr/local/go/bin" command -v go || true)
if [ -z "$go" ]; then
    echo "error: building hobo-agent needs Go: brew install go" >&2
    exit 1
fi

# The plugin's sandbox allows writes only under the scratch directory, and no network: the agent
# has no dependencies, and the installed toolchain is the one used.
mkdir -p "$scratch/cache" "$scratch/path"
export HOME="$scratch" GOCACHE="$scratch/cache" GOPATH="$scratch/path" GOTOOLCHAIN=local GOENV=off GOFLAGS= CGO_ENABLED=0

build() { # GOOS
    (cd "$source" && GOOS=$1 GOARCH=arm64 "$go" build -trimpath -buildvcs=false -ldflags="-s -w -buildid=" -o "$scratch/hobo-agent-$1" .)
}

build linux
build darwin
build windows

cat > "$output" <<SWIFT
// Generated by Agent/build.sh.
import Foundation

enum HoboAgentBinaries {
    static let linux = Data(base64Encoded: "$(base64 -i "$scratch/hobo-agent-linux")")!
    static let darwin = Data(base64Encoded: "$(base64 -i "$scratch/hobo-agent-darwin")")!
    static let windows = Data(base64Encoded: "$(base64 -i "$scratch/hobo-agent-windows")")!
}
SWIFT
